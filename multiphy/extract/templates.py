"""The templates tier: full-day rows for a day whose raw voltage is not read.

A unit's waveform is the sort's unwhitened template, as the day's normalized ``source/``
holds it. Its spike statistics and exact-condition fingerprints are recomputed from its
complete spike train over the analysis window, as the raw tier's full day recomputes them.
No voltage is read, so a templates-tier day has no halves and its rows no
``waveform_halves``. A unit with fewer than ``min_spikes`` spikes in the analysis window gets
an ineligible table row and no features. ``templates_methods`` is the ``METHODS.md`` text of
such a ``full/`` folder. This module imports no lab module.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
import sys

import numpy as np
import pandas as pd

from .full_day import TABLE_COLUMNS, _spike_features
from .unit_features import _checked_sample_spikes

TIER = 'templates'
TOO_FEW = 'Too few spikes in the analysis window.'
PREPROCESSING = ("Waveform: the sort's unwhitened template, in the sort's units; no voltage read. "
                 'Spike statistics from the complete spike train over the analysis window; native spike timestamps.')


def template_full_rows(source: dict, *, day: str, group: str, session_date: str, min_spikes: int,
                       bin_seconds: float = 0.05) -> dict:
    """Full-day table rows and features for every unit in ``source['entry']['single_unit_ids']``.

    ``source`` is ``read_source``'s result and must hold templates; a unit without one raises
    ``ValueError``. A unit with at least ``min_spikes`` spikes inside the analysis window gets
    an eligible row and a ``features`` entry: ``_spike_features`` over the analysis window plus
    its template (float32) as ``waveform`` and ``tier`` ``'templates'``. A unit with fewer gets
    an ineligible row with ``TOO_FEW`` and no features. Returns ``{'table', 'features',
    'geometry'}``: ``table`` has ``TABLE_COLUMNS``, ``features`` is keyed by unit id and
    ``geometry`` is ``{day: geometry}``.
    """
    entry, templates = source['entry'], source['templates']
    if templates is None:
        raise ValueError(f'Day {day} has no templates.')
    units = [str(unit) for unit in entry['single_unit_ids']]
    missing = [unit for unit in units if unit not in templates]
    if missing:
        raise ValueError(f'Unit {missing[0]} has no template.')
    start, stop = (int(value) for value in entry['analysis_window'])
    sample_rate = float(entry['sample_rate'])
    bin_samples = int(round(bin_seconds * sample_rate))  # the fingerprint bin _spike_features uses
    table, features = [], {}
    for unit in units:
        spikes = _checked_sample_spikes(source['spikes'][unit])
        eligible = int(((spikes >= start) & (spikes < stop)).sum()) >= min_spikes
        if eligible:
            feature = _spike_features(spikes, (start, stop), sample_rate, entry, bin_seconds)
            feature.update(waveform=np.asarray(templates[unit], dtype=np.float32), start_sample=start,
                           stop_sample=stop, sample_rate=sample_rate, su_type='SU', preprocessing=PREPROCESSING,
                           eligible=True, fingerprint_bin_seconds=bin_samples / sample_rate, tier=TIER)
            features[unit] = feature
        table.append(dict(cellid=unit, session_id=day, siteid=day, well=group, recording_group=group,
                          session_date=session_date, su_type='SU', eligible=eligible,
                          exclusion_reason='' if eligible else TOO_FEW))
    return {'table': pd.DataFrame(table, columns=list(TABLE_COLUMNS)), 'features': features,
            'geometry': {day: np.asarray(source['geometry']).copy()}}


def templates_methods(target: Path, full: dict) -> str:
    """The ``METHODS.md`` text of a templates-tier ``full/`` folder at ``target``."""
    table = full['table']
    n_eligible = int(table['eligible'].sum()) if len(table) else 0
    return f'''# Full-day unit rows from the sort's templates — methods notes

- **Output folder:** `{target}`
- **Artifacts:** `units.csv`, `features.npz`, `features.json`, `extras.npz`, `manifest.json`
- **Generated by:** `multiphy/extract/templates.py:template_full_rows()`, saved by `extract/full_day.py:save_full_day()` · **Env:** `{sys.executable}` · **Updated:** `{datetime.now(timezone.utc).date()}`
- **Units:** {len(table)} declared single units · {n_eligible} eligible
- **Tier:** `templates` · no raw voltage read · no halves

---

## Goal

One row per declared single unit over the whole analysis window of one recording day, without reading raw voltage: each unit's waveform is its sort's template.

## Data lineage

- `units.csv` ← `templates.py:template_full_rows()`; one row per unit in the source's single-unit list. `eligible` is `True` when the unit has at least `min_spikes` spikes in the analysis window. Otherwise `exclusion_reason` is `{TOO_FEW}` and the unit has no features.
- `features.npz` and `features.json` ← `template_full_rows()`. `waveform` is the unit's unwhitened template from `source/templates.npz`, as float32; for a phy sort it is the spike-count-weighted mean of `templates.npy` times `whitening_mat_inv.npy` over the templates the unit's spikes carry. Spike count, rate, baseline rate, interval histogram, autocorrelogram and exact-condition stimulus fingerprints are recomputed from the complete spike train over the analysis window, as in the raw tier. Each feature has `tier` `templates`, and no `waveform_halves` or waveform standard error.
- `extras.npz` ← empty; the templates tier carries no per-unit extras.
- `manifest.json` ← the sha256 of the four data files and the extraction metadata (`tier` `templates`, `halves_id` none); its own sha256 is the full-day id.

## Caveats

A template is the sort's model of a unit's waveform, in the sort's units and filtering, not a mean of recorded snippets in µV. Compare waveforms only between days of the same tier.
'''
